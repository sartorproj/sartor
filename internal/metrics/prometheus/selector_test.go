type sample struct {
	labels map[string]string
	value  string
}

func writeVector(w http.ResponseWriter, samples ...sample) {
	result := make([]map[string]interface{}, 0, len(samples))
	for _, s := range samples {
		labels := s.labels
		if labels == nil {
			labels = map[string]string{}
		}
		result = append(result, map[string]interface{}{
			"metric": labels,
			"value":  []interface{}{1234567890.123, s.value},
		})
	}
	w.Header().Set("Content-Type", "application/json")
	_ = json.NewEncoder(w).Encode(map[string]interface{}{
		"status": "success",
		"data":   map[string]interface{}{"resultType": "vector", "result": result},
	})
}

func TestPodNameRegex(t *testing.T) {
	deploy := func(name string) Workload { return Workload{Kind: KindDeployment, Name: name} }
	sts := func(name string) Workload { return Workload{Kind: KindStatefulSet, Name: name} }
	ds := func(name string) Workload { return Workload{Kind: KindDaemonSet, Name: name} }

	tests := []struct {
		name     string
		workload Workload
		pod      string
		want     bool
	}{
		// Deployment
		{"deployment pod", deploy("backend"), "backend-7d9f8c6b5-x2bqz", true},
		{"deployment short hash", deploy("backend"), "backend-5b4-x2bqz", true},
		{"deployment 10 char hash", deploy("backend"), "backend-7d9f8c6b5z-x2bqz", true},
		{"prefix of another deployment", deploy("backend"), "backend-cron-jobs-7d9f8c6b5-x2bqz", false},
		{"prefix of another deployment (word-addin)", deploy("word-addin"), "word-addin-backend-7d9f8c6b5-x2bqz", false},
		{"cronjob pods sharing the prefix", deploy("backend"), "backend-cron-jobs-29374650-x2bqz", false},
		{"same-named daemonset pod", deploy("agent"), "agent-x2bqz", false},
		{"same-named statefulset pod", deploy("db"), "db-0", false},
		{"suffix too short", deploy("backend"), "backend-7d9f8c6b5-x2bq", false},
		{"suffix too long", deploy("backend"), "backend-7d9f8c6b5-x2bqzz", false},
		{"hash with vowels is not generated by k8s", deploy("backend"), "backend-abcde-x2bqz", false},
		{"name only", deploy("backend"), "backend", false},
		{"different name sharing suffix", deploy("backend"), "my-backend-7d9f8c6b5-x2bqz", false},
		// Regex metacharacters are literal.
		{"dot in name matches literally", deploy("app.v1"), "app.v1-7d9f8c6b5-x2bqz", true},
		{"dot in name is not a wildcard", deploy("app.v1"), "appxv1-7d9f8c6b5-x2bqz", false},
		{"plus in name", deploy("a+"), "aa-7d9f8c6b5-x2bqz", false},
		{"alternation in name", deploy("a|b"), "b-7d9f8c6b5-x2bqz", false},
		{"alternation in name literal", deploy("a|b"), "a|b-7d9f8c6b5-x2bqz", true},
		// StatefulSet
		{"statefulset ordinal 0", sts("db"), "db-0", true},
		{"statefulset ordinal 9", sts("db"), "db-9", true},
		{"statefulset ordinal 10", sts("db"), "db-10", true},
		{"statefulset ordinal 123", sts("db"), "db-123", true},
		{"statefulset ordinal 9999", sts("db"), "db-9999", true},
		{"statefulset leading zero", sts("db"), "db-01", false},
		{"statefulset five digits (daemonset-like suffix)", sts("db"), "db-24567", false},
		{"statefulset prefix of another statefulset", sts("db"), "db-replica-0", false},
		{"statefulset vs deployment pod", sts("db"), "db-7d9f8c6b5-x2bqz", false},
		{"statefulset with dot", sts("kafka.broker"), "kafkaxbroker-0", false},
		// DaemonSet
		{"daemonset pod", ds("agent"), "agent-x2bqz", true},
		{"daemonset all-digit suffix", ds("agent"), "agent-24567", true},
		{"daemonset vs same-named deployment pod", ds("agent"), "agent-7d9f8c6b5-x2bqz", false},
		{"daemonset vs same-named statefulset pod", ds("agent"), "agent-0", false},
		{"daemonset prefix of another daemonset", ds("agent"), "agent-extra-x2bqz", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			expr, err := PodNameRegex(tt.workload)
			require.NoError(t, err)
			// Prometheus and VictoriaMetrics fully anchor regex matchers (RE2).
			re := regexp.MustCompile("^(?:" + expr + ")$")
			assert.Equal(t, tt.want, re.MatchString(tt.pod), "regex %s vs pod %s", expr, tt.pod)
		})
	}
}

