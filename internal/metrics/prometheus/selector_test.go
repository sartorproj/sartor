func TestClient_GetTimeSeriesMetrics_Query(t *testing.T) {
	tests := []struct {
		name        string
		ownerSeries bool
		resource    string
		wantMetric  string
	}{
		{"cpu regex", false, "cpu", "container_cpu_usage_seconds_total"},
		{"memory regex", false, "memory", "container_memory_working_set_bytes"},
		{"cpu join", true, "cpu", "container_cpu_usage_seconds_total"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var mu sync.Mutex
			var rangeQueries []string
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				if r.URL.Path == "/api/v1/query_range" {
					mu.Lock()
					rangeQueries = append(rangeQueries, r.FormValue("query"))
					mu.Unlock()
					w.Header().Set("Content-Type", "application/json")
					_, _ = w.Write([]byte(`{"status":"success","data":{"resultType":"matrix","result":[]}}`))
					return
				}
				if tt.ownerSeries {
					writeVector(w, sample{value: "1"})
				} else {
					writeVector(w)
				}
			}))
			defer server.Close()

			client, err := NewClient(Config{URL: server.URL})
			require.NoError(t, err)
			_, err = client.GetTimeSeriesMetrics(context.Background(), "prod",
				Workload{Kind: KindDeployment, Name: "backend"}, "app", tt.resource, time.Hour)
			require.NoError(t, err)
			require.Len(t, rangeQueries, 1)
			q := rangeQueries[0]
			_, err = metricsql.Parse(q)
			require.NoError(t, err, q)
			assert.True(t, strings.HasPrefix(q, "max("), q)
			assert.Contains(t, q, tt.wantMetric)
			assert.Contains(t, q, `container="app"`)
			assert.Equal(t, tt.ownerSeries, strings.Contains(q, "kube_replicaset_owner"), q)
		})
	}
}

// TestClient_RejectsPromQLInjection checks that user-controlled names that are
// not valid Kubernetes names never reach the backend.
func TestClient_RejectsPromQLInjection(t *testing.T) {
	tests := []struct {
		name      string
		namespace string
		workload  string
		container string
	}{
		{"quote in namespace", `prod"} or vector(1) or up{a="`, "web", "app"},
		{"brace in workload", "prod", `web"}) or vector(1) #`, "app"},
		{"regex wildcard in workload", "prod", "web.*", "app"},
		{"regex alternation in workload", "prod", "web|db", "app"},
		{"quote in container", "prod", "web", `app",container!="`},
		{"newline in container", "prod", "web", "app\n"},
		{"uppercase namespace", "Prod", "web", "app"},
		{"empty namespace", "", "web", "app"},
		{"empty container", "prod", "web", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var calls int
			server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
				calls++
				writeVector(w)
			}))
			defer server.Close()
			client, err := NewClient(Config{URL: server.URL})
			require.NoError(t, err)

			w := Workload{Kind: KindDeployment, Name: tt.workload}
			_, err = client.GetTimeSeriesMetrics(context.Background(), tt.namespace, w, tt.container, "cpu", time.Hour)
			assert.Error(t, err)
			if tt.container != "" {
				_, err = client.GetContainerMetrics(context.Background(), tt.namespace, w, time.Hour)
				if tt.namespace == "prod" && tt.workload == "web" {
					assert.NoError(t, err, "only the container is invalid")
				} else {
					assert.Error(t, err)
				}
			}
			if tt.namespace != "prod" || tt.workload != "web" {
				assert.Zero(t, calls, "no query may be sent for invalid input")
			}
		})
	}
}
