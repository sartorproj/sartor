// queryRecorder is a fake Prometheus API that records queries and answers
// the kube-state-metrics probe according to ownerSeries.
type queryRecorder struct {
	mu          sync.Mutex
	queries     []string
	ownerSeries bool
	samples     []sample
}

func (q *queryRecorder) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	query := r.FormValue("query")
	q.mu.Lock()
	q.queries = append(q.queries, query)
	q.mu.Unlock()
	if strings.HasPrefix(query, "count(kube_") {
		if q.ownerSeries {
			writeVector(w, sample{value: "3"})
		} else {
			writeVector(w)
		}
		return
	}
	writeVector(w, q.samples...)
}

func (q *queryRecorder) metricQueries() []string {
	q.mu.Lock()
	defer q.mu.Unlock()
	var out []string
	for _, query := range q.queries {
		if !strings.HasPrefix(query, "count(kube_") {
			out = append(out, query)
		}
	}
	return out
}

var podMatcherRe = regexp.MustCompile(`pod=~("(?:[^"\\]|\\.)*")`)

func TestClient_GetContainerMetrics_PodMatching(t *testing.T) {
	tests := []struct {
		name         string
		workload     Workload
		ownerSeries  bool
		wantJoin     string
		wantPodRegex string
	}{
		{
			name:         "deployment regex fallback",
			workload:     Workload{Kind: KindDeployment, Name: "word-addin"},
			wantPodRegex: "^word-addin-[bcdfghjklmnpqrstvwxz2456789]{1,10}-[bcdfghjklmnpqrstvwxz2456789]{5}$",
		},
		{
			name:         "statefulset regex fallback with metacharacters",
			workload:     Workload{Kind: KindStatefulSet, Name: "kafka.broker"},
			wantPodRegex: `^kafka\.broker-(0|[1-9][0-9]{0,3})$`,
		},
		{
			name:         "daemonset regex fallback",
			workload:     Workload{Kind: KindDaemonSet, Name: "agent"},
			wantPodRegex: "^agent-[bcdfghjklmnpqrstvwxz2456789]{5}$",
		},
		{
			name:         "deployment owner join",
			workload:     Workload{Kind: KindDeployment, Name: "backend"},
			ownerSeries:  true,
			wantJoin:     `kube_replicaset_owner{namespace="prod", owner_kind="Deployment", owner_name="backend"}`,
			wantPodRegex: "backend-.+",
		},
		{
			name:         "statefulset owner join",
			workload:     Workload{Kind: KindStatefulSet, Name: "db"},
			ownerSeries:  true,
			wantJoin:     `kube_pod_owner{namespace="prod", owner_kind="StatefulSet", owner_name="db"}`,
			wantPodRegex: "db-.+",
		},
		{
			name:         "daemonset owner join",
			workload:     Workload{Kind: KindDaemonSet, Name: "agent"},
			ownerSeries:  true,
			wantJoin:     `kube_pod_owner{namespace="prod", owner_kind="DaemonSet", owner_name="agent"}`,
			wantPodRegex: "agent-.+",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			rec := &queryRecorder{ownerSeries: tt.ownerSeries}
			server := httptest.NewServer(rec)
			defer server.Close()

			client, err := NewClient(Config{URL: server.URL})
			require.NoError(t, err)
			_, err = client.GetContainerMetrics(context.Background(), "prod", tt.workload, 168*time.Hour)
			require.NoError(t, err)

			queries := rec.metricQueries()
			require.Len(t, queries, 4)
			for _, q := range queries {
				_, err := metricsql.Parse(q)
				require.NoError(t, err, "query must be valid MetricsQL: %s", q)
				assert.Contains(t, q, "[7d:5m]")
				assert.Contains(t, q, "max by (container)")
				assert.Contains(t, q, `namespace="prod"`)

				m := podMatcherRe.FindStringSubmatch(q)
				require.NotNil(t, m, "no pod matcher in %s", q)
				podRegex, err := strconv.Unquote(m[1])
				require.NoError(t, err)
				assert.Equal(t, tt.wantPodRegex, podRegex)

				if tt.wantJoin != "" {
					assert.Contains(t, q, tt.wantJoin)
					assert.Contains(t, q, "* on (namespace, pod) group_left()")
				} else {
					assert.NotContains(t, q, "kube_pod_owner")
				}
			}
		})
	}
}

